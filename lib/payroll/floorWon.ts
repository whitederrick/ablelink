// lib/payroll/floorWon.ts
// 원 단위 절사(버림) — 부동소수점 오차로 정확히 떨어지는 값이 1원 모자라게 내림되는 것을 막는다.
//
// 2026-10-08 감사 P2: Math.floor(grossPay * 0.009)처럼 정수×요율을 바로 내림하면 0.009가 2진수로 정확히 표현되지
//  않아 9000이어야 할 값이 8999.999999999998이 되어 8999가 된다(고용보험 290개 급여 구간 중 127개에서 1원 부족).
//  요율은 소수 7자리 이내(%는 4자리 → 비율 6자리)라 곱의 진짜 값은 1e-7의 배수 — 소수 7자리로 먼저 맞추면 오차만 제거되고 정상 소수부는 그대로 절사된다.

export function floorWon(x: number): number {
  return Math.floor(Number(x.toFixed(7)));
}
